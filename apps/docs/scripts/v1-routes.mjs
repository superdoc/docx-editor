#!/usr/bin/env node

/**
 * Every URL the V1 documentation answers, and what V2 does with each one.
 *
 * The cutover repointed docs.superdoc.dev at this app. Anything the registry
 * misses stops resolving: the export has no SPA fallback, so an unmapped path
 * returns the 404 page rather than reaching V1. URLs published inside released
 * packages must either resolve directly in V2 or have a V1 disposition because
 * they keep being opened long after the version that printed them.
 *
 * V1 is frozen. Its route contract was captured once into config/v1-manifest.json
 * and is not rediscovered: the source tree it was assembled from no longer
 * lives in this repository, and the deployment it describes no longer changes.
 * The archive origin recorded in that manifest serves every route dispositioned
 * as `archive`.
 */

import { execFile } from 'node:child_process';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import process from 'node:process';
import { promisify } from 'node:util';
import { fileURLToPath } from 'node:url';

const execFileAsync = promisify(execFile);

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const publicRoot = resolve(scriptDirectory, '../../..');
const defaultManifestPath = resolve(scriptDirectory, '../config/v1-manifest.json');
const defaultDispositionsPath = resolve(scriptDirectory, '../config/v1-dispositions.json');
const defaultOutputDirectory = resolve(scriptDirectory, '../out');

// Where a released package could carry a documentation link. Scoped to
// published surfaces: the docs apps link to each other and are not installed by
// anyone.
const shippedLinkRoots = ['packages', 'apps/cli', 'apps/mcp', 'apps/vscode-ext'];
const defaultRoutesPath = resolve(scriptDirectory, '../config/routes.json');

// Where a V1 URL can end up. Every inventoried route gets exactly one.
export const dispositionKinds = new Set(['v2', 'archive', 'retired']);

export const archiveHost = 'https://docs-v1.superdoc.dev';

// Separates this command's output from the V2 tooling's. Cloudflare ignores
// comment lines, and the marker lets a rerun replace its own rules without
// mistaking them for someone else's.
const v1SectionMarker = '# V1 route dispositions -- generated by scripts/v1-routes.mjs\n';

/**
 * The frozen V1 route contract.
 *
 * Read, never derived. The manifest was captured once from the V1 source tree
 * and its deployed sitemap, then crawled to separate the URLs the site answers
 * from the candidates it never served. That source tree is gone and the
 * deployment behind it no longer changes, so there is nothing to rediscover:
 * a difference between this file and reality would mean the archive moved, not
 * that the capture went stale.
 */
export async function readV1Manifest(manifestPath = defaultManifestPath) {
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  const problems = validateManifest(manifest);
  if (problems.length > 0) {
    throw new Error(['The frozen V1 manifest is not usable:', ...problems.map((line) => `- ${line}`)].join('\n'));
  }
  return {
    capture: manifest.capture,
    live: manifest.live,
    dead: manifest.dead,
    candidates: manifest.candidates,
    redirects: manifest.redirects,
    redirectPatterns: manifest.redirectPatterns,
  };
}

/**
 * Rejects a manifest that could not describe a real V1 deployment.
 *
 * A frozen file has no generator left to trust, so the shape is checked on
 * every read. The provenance fields matter as much as the routes: a commit
 * alone is ambiguous, because this documentation is mirrored into another
 * repository under a different path. Repository, commit, and path are only
 * reproducible together, and without an archive origin a future reader cannot
 * tell where the archived URLs now resolve.
 */
export function validateManifest(manifest) {
  const problems = [];
  if (!manifest || typeof manifest !== 'object' || Array.isArray(manifest)) {
    return ['The manifest must be an object.'];
  }

  for (const field of ['live', 'dead', 'candidates']) {
    if (!Array.isArray(manifest[field])) problems.push(`${field} must be an array of root-relative paths.`);
    else if (manifest[field].some((path) => typeof path !== 'string' || !path.startsWith('/'))) {
      problems.push(`${field} must contain only root-relative paths.`);
    }
  }

  for (const field of ['redirects', 'redirectPatterns']) {
    if (!Array.isArray(manifest[field])) {
      problems.push(`${field} must be an array of { source, destination } entries.`);
      continue;
    }
    if (manifest[field].some((entry) => typeof entry?.source !== 'string' || typeof entry?.destination !== 'string')) {
      problems.push(`${field} entries must each have a source and a destination.`);
    }
  }

  const capture = manifest.capture;
  if (!capture || typeof capture !== 'object' || Array.isArray(capture)) {
    problems.push('capture must record where and when this contract was taken.');
  } else {
    for (const field of [
      'capturedFrom',
      'capturedAt',
      'sourceRepository',
      'sourceCommit',
      'sourcePath',
      'archiveOrigin',
    ]) {
      if (typeof capture[field] !== 'string' || capture[field].trim().length === 0) {
        problems.push(`capture.${field} must be recorded so the capture stays reproducible.`);
      }
    }
    if (typeof capture.archiveOrigin === 'string' && capture.archiveOrigin !== archiveHost) {
      problems.push(`capture.archiveOrigin must match the archive host this app redirects to: ${archiveHost}`);
    }
  }

  if (Array.isArray(manifest.live) && manifest.live.length === 0) {
    problems.push('live must not be empty; V1 answered routes and an empty capture would silently pass every check.');
  }

  return problems;
}

function bySource(left, right) {
  return left.source < right.source ? -1 : left.source > right.source ? 1 : 0;
}

export function parseDispositions(value) {
  if (!value || typeof value !== 'object' || Array.isArray(value) || !Array.isArray(value.dispositions)) {
    throw new Error('Disposition registry must be an object with a dispositions array.');
  }

  const bySourcePath = new Map();
  for (const [index, entry] of value.dispositions.entries()) {
    if (!entry || typeof entry !== 'object' || Array.isArray(entry)) {
      throw new Error(`dispositions[${index}] must be an object.`);
    }
    const { source, kind, destination, reason } = entry;
    if (typeof source !== 'string' || !source.startsWith('/')) {
      throw new Error(`dispositions[${index}].source must be a root-relative V1 path.`);
    }
    if (!dispositionKinds.has(kind)) {
      throw new Error(
        `dispositions[${index}].kind must be one of ${[...dispositionKinds].join(', ')}: ${String(kind)}`,
      );
    }
    if (kind === 'v2' && (typeof destination !== 'string' || !destination.startsWith('/'))) {
      throw new Error(`dispositions[${index}].destination must be the V2 path that replaces ${source}.`);
    }
    // The V2 export sets trailingSlash, so its pages are directory indexes and
    // the canonical route ends in a slash. A destination without one sends the
    // visitor to a URL that immediately redirects again, which is a wasted hop
    // on every inbound V1 link.
    if (kind === 'v2' && destination !== '/' && !destination.endsWith('/')) {
      throw new Error(
        `dispositions[${index}].destination must be a canonical V2 route ending in a slash: ${destination}`,
      );
    }
    if (kind !== 'v2' && destination !== undefined) {
      throw new Error(`dispositions[${index}].destination only applies to a v2 replacement: ${source}`);
    }
    if (kind === 'retired' && (typeof reason !== 'string' || reason.trim().length === 0)) {
      throw new Error(`dispositions[${index}].reason must explain why ${source} was retired without a replacement.`);
    }
    if (bySourcePath.has(source)) {
      throw new Error(`Two dispositions claim the same V1 route: ${source}`);
    }
    bySourcePath.set(source, { source, kind, destination, reason });
  }
  return bySourcePath;
}

/**
 * Checks the registry against the routes V1 answers and the routes V2 builds.
 *
 * `manifest.live` is the authority for what needs covering: it is what the
 * crawl confirmed the site returns, which is neither the file listing nor the
 * candidate union. Redirect sources are already part of it, so this reads one
 * list rather than reassembling one.
 */
export function validateDispositions({ manifest, dispositions, v2Routes, shippedLinks = [] }) {
  const problems = [];
  const deadRoutes = new Set(manifest.dead ?? []);
  const patternPrefixes = (manifest.redirectPatterns ?? []).map(({ source }) => source.split(/[:*]/u)[0]);

  const covered = (path) =>
    v2Routes.has(path) ||
    dispositions.has(path) ||
    patternPrefixes.some((prefix) => prefix.length > 1 && path.startsWith(prefix));

  for (const source of manifest.live ?? []) {
    if (!dispositions.has(source)) {
      problems.push(`No disposition for V1 route: ${source}`);
    }
  }

  // A disposition for a URL the site never answered would publish a redirect
  // for a path that only ever 404ed, which is noise in the rule budget and
  // implies coverage that was never real.
  for (const source of dispositions.keys()) {
    if (deadRoutes.has(source)) {
      problems.push(`Disposition for a V1 route the site does not answer: ${source}`);
    }
  }

  for (const [source, entry] of dispositions) {
    if (entry.kind !== 'v2') continue;
    // The route manifest records routes with a trailing slash and the
    // destination may be written either way, so both sides are normalised
    // before comparing.
    if (!v2Routes.has(entry.destination.replace(/\/$/u, ''))) {
      problems.push(`V2 replacement does not exist: ${source} -> ${entry.destination}`);
    }
    // A destination that is itself redirected would cost every visitor an extra
    // hop and lose PageRank.
    const onward = dispositions.get(entry.destination);
    if (onward) {
      problems.push(`Redirect chain: ${source} -> ${entry.destination}, which is itself redirected.`);
    }
  }

  for (const link of shippedLinks) {
    if (!covered(link)) {
      problems.push(`Released packages link to a route with no V2 page or V1 disposition: ${link}`);
    }
  }

  return problems;
}

/**
 * Translates a Mintlify redirect pattern into a Cloudflare Pages rule.
 *
 * Mintlify writes `/modules/:path*`; Cloudflare wants `/modules/*` with the
 * captured remainder as `:splat`.
 */
export function toCloudflarePattern({ source, destination }) {
  const from = source.replace(/\/:[A-Za-z]+\*?$/u, '/*').replace(/\/\*$/u, '/*');
  const to = destination.replace(/\/:[A-Za-z]+\*?$/u, '/:splat').replace(/\/\*$/u, '/:splat');
  return { source: from, destination: to };
}

/**
 * Renders the registry as Cloudflare Pages redirect rules.
 *
 * Order matters, and it is not alphabetical. Cloudflare takes the first
 * matching rule, so `/modules/*` placed above `/modules/collaboration/*` would
 * swallow the collaboration URLs and send them somewhere wrong. Exact rules go
 * first because they can never be shadowed, then patterns longest-first so the
 * most specific one always wins.
 *
 * Archive redirects are 302 while the mapping is still being filled in: a page
 * that later gains a real V2 replacement should not have been cached as a
 * permanent move to the archive.
 *
 * `terminalPaths` maps a V1 redirect source to where V1 itself sends it. An
 * archive rule pointing at a path V1 redirects again would cost every visitor a
 * second hop, so the rule targets the destination directly.
 */
export function renderDispositionRedirects(dispositions, redirectPatterns = [], terminalPaths = new Map()) {
  const patterns = [...redirectPatterns]
    .map(toCloudflarePattern)
    .sort((left, right) => right.source.length - left.source.length);
  const patternFor = (path) => patterns.find(({ source }) => path.startsWith(source.slice(0, -1)));
  const patternResult = (path) => {
    const pattern = patternFor(path);
    if (!pattern) return undefined;
    return pattern.destination.replace(':splat', path.slice(pattern.source.length - 1));
  };

  const exact = [];
  for (const { source, kind, destination } of dispositions.values()) {
    // A V1 URL whose V2 replacement sits at the same path needs no rule: the
    // export serves that page directly, and a redirect from /x to /x/ would
    // only add a hop to something the platform already resolves. Most of the
    // registry is this case once the pages own the root namespace.
    if (kind === 'v2' && destination === `${source}/`) continue;

    const terminal = terminalPaths.get(source) ?? source;
    // Skip only when the wildcard already produces this exact destination.
    // Suppressing every wildcard-covered source would discard the more specific
    // V1 redirects that exist precisely because the pattern gets them wrong:
    // /modules/collaboration/backend resolves to /editor/collaboration/
    // configuration in V1, not to the /editor/collaboration/backend the pattern
    // would derive.
    if (kind === 'archive' && patternResult(source) === terminal) continue;

    const target =
      kind === 'v2'
        ? destination
        : kind === 'archive'
          ? // V1 answers some of these with a redirect of its own. Pointing at
            // the path it would forward from costs a second hop, so the rule
            // targets where V1 ends up.
            `${archiveHost}${terminal}`
          : undefined;
    // Retired routes fall through to the 404 page, which offers a search for
    // the requested path and a link into the archive. A blanket redirect home
    // would read as a soft 404 and lose what the visitor asked for.
    if (target === undefined) continue;
    const status = kind === 'v2' ? 301 : 302;
    exact.push(`${source} ${target} ${status}`);
    // Cloudflare matches sources exactly, so /old and /old/ are distinct rules
    // and a visitor arriving at the other form would miss the redirect.
    if (source !== '/') exact.push(`${source}/ ${target} ${status}`);
  }

  const rules = [
    ...exact.sort(),
    ...patterns.map(({ source, destination }) => `${source} ${archiveHost}${destination} 302`),
  ];
  if (rules.length > 2000) {
    throw new Error(`Redirect output exceeds the Cloudflare Pages limit of 2,000 rules: ${rules.length}`);
  }
  return rules.join('\n');
}

/**
 * Documentation URLs published inside released packages.
 *
 * These links were printed by package versions people keep installed. Each one
 * must resolve directly in V2 or through the V1 disposition registry because
 * fixing the source later cannot update copies already installed.
 */
export async function collectShippedLinks(searchRoots) {
  // git grep exits 1 both when nothing matched and when a path does not exist,
  // so the roots are checked first: otherwise a renamed directory would read as
  // "no links found" and the check would pass by having stopped working.
  const missing = [];
  for (const root of searchRoots) {
    try {
      await readdir(resolve(publicRoot, root));
    } catch {
      missing.push(root);
    }
  }
  if (missing.length > 0) {
    throw new Error(`Cannot scan released packages, these paths do not exist: ${missing.join(', ')}`);
  }

  let stdout;
  try {
    ({ stdout } = await execFileAsync(
      'git',
      ['grep', '-hoE', 'https://docs\\.superdoc\\.dev/[a-zA-Z0-9/_#.?=-]*', '--', ...searchRoots],
      { cwd: publicRoot, maxBuffer: 32 * 1024 * 1024 },
    ));
  } catch (error) {
    // `git grep` exits 1 when nothing matched, which is a real answer. Anything
    // else -- a bad path, a missing git, a broken pattern -- must not be read as
    // "no links found", or this check would pass precisely because it stopped
    // working.
    if (error?.code === 1 && !String(error?.stderr ?? '').trim()) stdout = '';
    else throw new Error(`Could not scan released packages for documentation links: ${error?.stderr || error}`);
  }

  const links = stdout
    .split('\n')
    .map((line) =>
      line
        .replace('https://docs.superdoc.dev', '')
        .replace(/[#?].*$/u, '')
        .replace(/\/$/u, ''),
    )
    .filter((link) => link.startsWith('/'));
  return [...new Set(links)].sort();
}

/**
 * Where V1 finally lands for each of its own redirect sources.
 *
 * Follows the chain, so a source pointing at another source resolves to the end
 * of it. A cycle resolves to the last path before the repeat rather than
 * looping.
 */
export function resolveTerminalPaths(redirects) {
  const bySource = new Map(redirects.map(({ source, destination }) => [source, destination]));
  const terminal = new Map();
  for (const [source] of bySource) {
    const seen = new Set([source]);
    let current = bySource.get(source);
    while (bySource.has(current) && !seen.has(current)) {
      seen.add(current);
      current = bySource.get(current);
    }
    // The fragment is part of where V1 sends this request. Cloudflare carries a
    // fragment from the incoming URL, but these sources have none of their own,
    // so dropping it would land the visitor on the page instead of the section
    // the redirect names.
    terminal.set(source, current);
  }
  return terminal;
}

/**
 * Writes the V1 redirect rules into the Cloudflare Pages redirect file.
 *
 * Appended to whatever the V2 route tooling already generated, and checked
 * against the platform limit as a combined artifact: the two sets share one
 * budget and one namespace, and a V1 rule that collided with a V2 one would
 * silently win or lose depending on order.
 */
export async function appendDispositionRedirects({
  dispositionsPath = defaultDispositionsPath,
  outputDirectory = defaultOutputDirectory,
  manifestPath = defaultManifestPath,
} = {}) {
  const [dispositions, manifest] = await Promise.all([
    readFile(dispositionsPath, 'utf8').then((raw) => parseDispositions(JSON.parse(raw))),
    readV1Manifest(manifestPath),
  ]);

  const outputPath = resolve(outputDirectory, '_redirects');
  const existing = await readFile(outputPath, 'utf8').catch(() => '');
  // Everything after the marker is this command's own previous output, so it is
  // dropped before regenerating: running twice produces the same file instead
  // of reporting its own rules as collisions. Anything before the marker
  // belongs to the V2 route tooling, and a source appearing in both is still a
  // real conflict.
  const existingRules = existing.split(v1SectionMarker)[0].split('\n').filter(Boolean);
  const existingBySource = new Map(existingRules.map((rule) => [rule.split(' ')[0], rule]));

  // A V1 route whose V2 replacement later moved is redirected by both tools to
  // the same place. That rule is already in the file, so it is dropped here;
  // only a source the two tools send somewhere different is a real conflict.
  const rendered = renderDispositionRedirects(
    dispositions,
    manifest.redirectPatterns,
    resolveTerminalPaths(manifest.redirects),
  )
    .split('\n')
    .filter(Boolean)
    .filter((rule) => existingBySource.get(rule.split(' ')[0]) !== rule);

  const collisions = rendered.filter((rule) => existingBySource.has(rule.split(' ')[0]));
  if (collisions.length > 0) {
    throw new Error(
      [
        'V1 redirect rules collide with rules the V2 tooling already generated:',
        ...collisions.map((rule) => `- ${rule.split(' ')[0]}`),
        '',
        'One of the two would silently win. Reconcile the sources before generating.',
      ].join('\n'),
    );
  }

  const combined = [...existingRules, ...rendered];
  if (combined.length > 2000) {
    throw new Error(
      `Combined redirect output exceeds the Cloudflare Pages limit of 2,000 rules: ${combined.length} ` +
        `(${existingRules.length} from V2 routing, ${rendered.length} from V1 dispositions).`,
    );
  }

  await writeFile(outputPath, `${existingRules.join('\n')}\n${v1SectionMarker}${rendered.join('\n')}\n`);
  return { outputPath, v1RuleCount: rendered.length, totalRuleCount: combined.length };
}

/**
 * Checks the frozen manifest against itself.
 *
 * This replaces the drift check that used to ask whether the V1 source tree had
 * changed since the crawl. That question is answered permanently: the tree is
 * gone. What can still go wrong is someone hand-editing the manifest, so the
 * remaining invariant is internal. Every candidate the capture inventoried must
 * have been crawled, and every crawled path must have been a candidate.
 */
export function validateManifestConsistency(manifest) {
  const problems = [];
  const candidates = new Set([...manifest.candidates, ...manifest.redirects.map(({ source }) => source)]);
  const captured = new Set([...manifest.live, ...manifest.dead]);

  for (const path of [...candidates].filter((candidate) => !captured.has(candidate)).sort()) {
    problems.push(`Inventoried but never crawled, so nothing knows whether V1 answers it: ${path}`);
  }
  for (const path of [...captured].filter((entry) => !candidates.has(entry)).sort()) {
    problems.push(`Crawled but not in the inventory that produced the crawl: ${path}`);
  }
  return problems;
}

async function run() {
  const [, , command = 'check'] = process.argv;
  const manifest = await readV1Manifest();

  if (command === 'inventory') {
    console.log(`${manifest.live.length} V1 URLs the archive answers, ${manifest.dead.length} candidates it does not.`);
    console.log(`${manifest.redirectPatterns.length} wildcard redirect patterns.`);
    console.log(`Captured from ${manifest.capture.sourcePath} at ${manifest.capture.sourceCommit}.`);
    console.log(`Archived at ${manifest.capture.archiveOrigin}.`);
    return;
  }

  if (command === 'generate') {
    const result = await appendDispositionRedirects();
    console.log(
      `Appended ${result.v1RuleCount} V1 redirect rules (${result.totalRuleCount} total) to ${result.outputPath}.`,
    );
    return;
  }

  const v2Routes = new Set(
    JSON.parse(await readFile(defaultRoutesPath, 'utf8')).routes.map((route) => route.replace(/\/$/u, '')),
  );
  const shippedLinks = await collectShippedLinks(shippedLinkRoots);
  const dispositions = parseDispositions(JSON.parse(await readFile(defaultDispositionsPath, 'utf8')));

  const inconsistencies = validateManifestConsistency(manifest);
  if (inconsistencies.length > 0) {
    console.error(
      ['The frozen V1 manifest is internally inconsistent:', '', ...inconsistencies.map((line) => `- ${line}`)].join(
        '\n',
      ),
    );
    process.exitCode = 1;
    return;
  }

  // The scan finding nothing would be indistinguishable from the scan breaking,
  // and the broken case passes. Released packages do carry documentation links,
  // so zero means the check stopped working.
  if (shippedLinks.length === 0) {
    throw new Error(
      'Found no documentation links in released packages. That is not expected, so the scan is likely broken.',
    );
  }

  const problems = validateDispositions({ manifest, dispositions, v2Routes, shippedLinks });
  if (problems.length > 0) {
    console.error(['V1 route disposition check failed:', '', ...problems.map((line) => `- ${line}`)].join('\n'));
    process.exitCode = 1;
    return;
  }
  console.log(
    `Checked ${dispositions.size} V1 route dispositions and ${shippedLinks.length} links published in released packages.`,
  );
}

const invokedScript = process.argv[1] ? resolve(process.argv[1]) : undefined;
if (invokedScript === fileURLToPath(import.meta.url)) {
  try {
    await run();
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
