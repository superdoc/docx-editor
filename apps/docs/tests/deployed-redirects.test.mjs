import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { test } from 'node:test';
import { parseCurrentRedirectRules, probeCurrentRedirects } from '../scripts/verify-current-redirects.mjs';

async function serve(t, handler) {
  const server = createServer(handler);
  await new Promise((resolve, reject) => {
    server.once('error', reject);
    server.listen(0, '127.0.0.1', resolve);
  });
  t.after(() => new Promise((resolve, reject) => server.close((error) => (error ? reject(error) : resolve()))));

  const address = server.address();
  assert.ok(address && typeof address === 'object');
  return `http://127.0.0.1:${address.port}`;
}

test('reads only current documentation rules from the deployed redirect file', () => {
  const rules = parseCurrentRedirectRules(
    [
      '/old /new/ 301',
      '/temporary /replacement/ 302',
      '# V1 route dispositions -- generated by scripts/v1-routes.mjs',
      '/legacy https://docs-v1.superdoc.dev/legacy 302',
      '',
    ].join('\n'),
  );

  assert.deepEqual(rules, [
    { source: '/old', destination: '/new/', status: 301 },
    { source: '/temporary', destination: '/replacement/', status: 302 },
  ]);
  assert.throws(() => parseCurrentRedirectRules('/old /new/ 301\n'), /cannot separate current redirects from V1/u);
});

test('accepts redirects that return the configured status, destination, and final page', async (t) => {
  const origin = await serve(t, (request, response) => {
    if (request.url === '/old') {
      response.writeHead(301, { location: '/new/' }).end();
      return;
    }
    if (request.url === '/temporary') {
      response.writeHead(302, { location: '/replacement/' }).end();
      return;
    }
    if (request.url === '/new/' || request.url === '/replacement/') {
      response.writeHead(200).end('found');
      return;
    }
    response.writeHead(404).end('missing');
  });

  const results = await probeCurrentRedirects(
    [
      { source: '/old', destination: '/new/', status: 301 },
      { source: '/temporary', destination: '/replacement/', status: 302 },
    ],
    { origin },
  );

  assert.deepEqual(results, [
    { source: '/old', destination: '/new/', status: 301 },
    { source: '/temporary', destination: '/replacement/', status: 302 },
  ]);
});

test('reports ignored rules, wrong destinations, and broken landing pages', async (t) => {
  const origin = await serve(t, (request, response) => {
    if (request.url === '/ignored') {
      response.writeHead(404).end('missing');
      return;
    }
    if (request.url === '/wrong-destination') {
      response.writeHead(301, { location: '/somewhere-else/' }).end();
      return;
    }
    if (request.url === '/broken-landing') {
      response.writeHead(301, { location: '/missing/' }).end();
      return;
    }
    response.writeHead(request.url === '/somewhere-else/' ? 200 : 404).end();
  });

  const results = await probeCurrentRedirects(
    [
      { source: '/ignored', destination: '/new/', status: 301 },
      { source: '/wrong-destination', destination: '/new/', status: 301 },
      { source: '/broken-landing', destination: '/missing/', status: 301 },
    ],
    { origin },
  );

  assert.equal(results[0].failure, 'got status 404');
  assert.match(results[1].failure, /got Location .*\/somewhere-else\//u);
  assert.match(results[2].failure, /destination returned 404/u);
});

test('retries a server error on the redirect and its landing page, then passes', async (t) => {
  const seen = new Map();
  const origin = await serve(t, (request, response) => {
    const count = (seen.get(request.url) ?? 0) + 1;
    seen.set(request.url, count);
    if (count === 1) {
      response.writeHead(500).end('busy');
      return;
    }
    if (request.url === '/old') {
      response.writeHead(301, { location: '/new/' }).end();
      return;
    }
    response.writeHead(request.url === '/new/' ? 200 : 404).end();
  });

  const results = await probeCurrentRedirects([{ source: '/old', destination: '/new/', status: 301 }], {
    origin,
    retryDelayMs: 0,
  });

  assert.deepEqual(results, [{ source: '/old', destination: '/new/', status: 301 }]);
  assert.equal(seen.get('/new/'), 2);
});

test('reports a redirect whose server error persists across every attempt', async (t) => {
  let requests = 0;
  const origin = await serve(t, (_request, response) => {
    requests++;
    response.writeHead(500).end('down');
  });

  const results = await probeCurrentRedirects([{ source: '/old', destination: '/new/', status: 301 }], {
    origin,
    retryDelayMs: 0,
  });

  assert.equal(results[0].failure, 'got status 500');
  assert.equal(requests, 3);
});
